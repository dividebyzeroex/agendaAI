import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import {expect,test} from 'vitest';
test('activation uses tenant RLS, compatible slots and non-test period counts',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to authenticated;
 create table estabelecimento(id uuid,user_id uuid,created_at timestamptz,trial_ends_at timestamptz,plano_expires_at timestamptz);
 create table servicos(id uuid,estabelecimento_id uuid,ativo boolean,duracao_min int);
 create table profissionais(id uuid,estabelecimento_id uuid,ativo boolean);
 create table profissional_servicos(profissional_id uuid,servico_id uuid,estabelecimento_id uuid);
 create table profissional_disponibilidades(profissional_id uuid,estabelecimento_id uuid,ativo boolean,dia_semana int,hora_inicio time,hora_fim time,intervalo_inicio time,intervalo_fim time);
 create table horarios_funcionamento(estabelecimento_id uuid,ativo boolean,dia_semana int,abre time,fecha time);
 create table agenda_events(estabelecimento_id uuid,status text,metadata jsonb,created_at timestamptz);
 create table clientes(estabelecimento_id uuid,created_at timestamptz);
 create table caixa_itens(estabelecimento_id uuid,created_at timestamptz);
 grant select on all tables in schema public to authenticated;
 alter table estabelecimento enable row level security;
 create policy tenant on estabelecimento to authenticated using(user_id=auth.uid());`);
 const a='10000000-0000-4000-8000-000000000001',b='20000000-0000-4000-8000-000000000001';
 const pro='30000000-0000-4000-8000-000000000001',service='40000000-0000-4000-8000-000000000001';
 await db.exec(`insert into estabelecimento values('${a}','${a}',now()-interval '2 days',now()+interval '28 days',null),('${b}','${b}',now(),now()+interval '30 days',null);
 insert into servicos values('${service}','${a}',true,30);
 insert into profissionais values('${pro}','${a}',true);
 insert into profissional_servicos values('${pro}','${service}','${a}');
 insert into profissional_disponibilidades values('${pro}','${a}',true,1,'09:00','12:00','10:00','11:00');
 insert into horarios_funcionamento values('${a}',true,1,'09:00','12:00');
 insert into agenda_events values('${a}','confirmado','{"origin":"public_booking"}',now()),('${a}','concluido','{}',now()),('${a}','cancelado','{}',now()),('${a}','confirmado','{"demo":true}',now()),('${a}','confirmado','{"test":true}',now()),('${b}','confirmado','{}',now()),('${a}','confirmado','{}',now()-interval '60 days');
 insert into clientes values('${a}',now()),('${b}',now());`);
 await db.exec(await readFile(new URL('../supabase/migrations/20261011152337_tenant_activation_summary.sql',import.meta.url),'utf8'));
 await db.exec('set role anon');await expect(db.query(`select tenant_activation_summary('${a}')`)).rejects.toThrow();
 await db.exec('reset role;set role authenticated');await db.query(`select set_config('request.jwt.claim.sub','${a}',false)`);
 const snapshot=async()=>((await db.query<{s:any}>(`select tenant_activation_summary('${a}') s`)).rows[0].s);
 expect(await snapshot()).toMatchObject({services_ready:true,staff_ready:true,schedule_ready:true,first_booking:true,appointments:2,completed:1,public_bookings:1,clients:1,during_trial:true});
 await expect(db.query(`select tenant_activation_summary('${b}')`)).rejects.toThrow('Estabelecimento indisponível');
 await db.exec(`reset role;update profissional_disponibilidades set intervalo_inicio='09:00',intervalo_fim='12:00';set role authenticated`);
 expect((await snapshot()).schedule_ready).toBe(false);
 await db.exec(`reset role;update profissional_disponibilidades set intervalo_inicio=null,intervalo_fim=null,hora_inicio='18:00',hora_fim='19:00';set role authenticated`);
 expect((await snapshot()).schedule_ready).toBe(false);
 await db.exec(`reset role;update estabelecimento set plano_expires_at=now()+interval '30 days' where id='${a}';set role authenticated`);
 expect((await snapshot()).during_trial).toBe(false);
 await db.close();
});
